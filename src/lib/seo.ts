import type { Metadata } from "next";
import { allowIndexing, site } from "@/data/site";

export const BASE_URL = site.url.replace(/\/$/, "");

export function absoluteUrl(path = "/") {
  const clean = path.startsWith("/") ? path : `/${path}`;
  return clean === "/" ? BASE_URL : `${BASE_URL}${clean}`;
}

type BuildMetaArgs = {
  title: string;
  description: string;
  path: string;
  /** Share image path under /public. Defaults to the site-wide card. */
  image?: string;
  type?: "website" | "article";
  noIndex?: boolean;
};

/**
 * Every page builds its metadata through here so titles, canonicals, Open
 * Graph and Twitter cards cannot drift apart.
 *
 * Share images are static files in /public/og, generated by
 * `npm run og` (scripts/generate-og.mjs): one site-wide card plus one per
 * service.
 */
export function buildMetadata({
  title,
  description,
  path,
  image = "/og/default.png",
  type = "website",
  noIndex = false,
}: BuildMetaArgs): Metadata {
  const url = absoluteUrl(path);
  const indexable = allowIndexing && !noIndex;

  return {
    // `absolute` opts out of the layout title template: each page owns its
    // whole title, which keeps them under ~60 characters.
    title: { absolute: title },
    description,
    alternates: { canonical: url },
    robots: indexable
      ? {
          index: true,
          follow: true,
          googleBot: { index: true, follow: true, "max-image-preview": "large", "max-snippet": -1 },
        }
      : { index: false, follow: true },
    openGraph: {
      title,
      description,
      url,
      siteName: site.name,
      locale: site.locale,
      type,
      images: [{ url: absoluteUrl(image), width: 1200, height: 630, alt: title }],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [absoluteUrl(image)],
    },
  };
}
